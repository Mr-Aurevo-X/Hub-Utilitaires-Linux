_STRINGS: dict[str, dict[str, str]] = {"fr": _FR, "en": _EN}


def normalize_language(code: object) -> str:
    raw = str(code or "fr").strip().lower().replace("_", "-")
    lang = raw.split("-", 1)[0]
    return lang if lang in _STRINGS else "fr"


def set_language(code: object) -> None:
    global _LANG
    _LANG = normalize_language(code)


def language() -> str:
    return _LANG


def t(key: str, **kwargs: object) -> str:
    table = _STRINGS.get(_LANG) or _STRINGS["fr"]
    text = table.get(key) or _STRINGS["fr"].get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, ValueError):
            return text
    return text
